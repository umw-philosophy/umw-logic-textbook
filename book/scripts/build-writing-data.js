#!/usr/bin/env node
'use strict';
/*
 * build-writing-data.js
 * Reads the book's Key Terms and Writing Prompts from the PreTeXt source and
 * writes the data files the Argument Feedback tool uses:
 *   writingfeedback/concepts.js         (Key Terms + writingfeedback/concept-settings.json)
 *   writingfeedback/writing-prompts.js  (end-of-chapter Writing Prompts)
 *
 * Run from anywhere:  node book/scripts/build-writing-data.js
 * Check only:         node book/scripts/build-writing-data.js --check   (exit 1 if the files are stale)
 * writingfeedback/logic-tests.js runs the check too.
 */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..', '..');
const SOURCE = path.join(ROOT, 'book', 'source');
const OUT = path.join(ROOT, 'writingfeedback');

const LATEX = [
  [/\{\\text\{\\textasciitilde\}\}/g, '~'], [/\\textasciitilde/g, '~'], [/\\mathcal\{(\w)\}/g, '$1'],
  [/\\supset/g, '⊃'], [/\\vee|\\lor/g, '∨'], [/\\cdot|\\land/g, '·'], [/\\equiv/g, '≡'], [/\\therefore/g, '∴'],
  [/\\sim|\\lnot/g, '~'], [/\\mid/g, '|'], [/\\bigl|\\bigr/g, ''], [/\\,/g, ' '], [/[{}]/g, ''],
];
const ENTITIES = { quot: '"', amp: '&', lt: '<', gt: '>', apos: "'", nbsp: ' ', mdash: '—', ndash: '–', hellip: '…' };

function plain(xml) {
  return xml
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<m>([\s\S]*?)<\/m>/g, (m, tex) => LATEX.reduce((t, [re, sym]) => t.replace(re, sym), tex).replace(/\s+/g, ' '))
    .replace(/<q>/g, '“').replace(/<\/q>/g, '”')
    .replace(/<sq>/g, '‘').replace(/<\/sq>/g, '’')
    .replace(/<[^>]+>/g, '')
    .replace(/&(#x?[0-9a-fA-F]+|\w+);/g, (m, e) => {
      if (e[0] === '#') return String.fromCodePoint(e[1] === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
      return ENTITIES[e] !== undefined ? ENTITIES[e] : m;
    })
    .replace(/\s+/g, ' ')
    .trim();
}

function chapterFiles() {
  const main = fs.readFileSync(path.join(SOURCE, 'main.ptx'), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const files = [];
  const re = /<xi:include\s+href="(chapters\/[^"]+\.ptx)"/g;
  let m;
  while ((m = re.exec(main))) files.push(m[1]);
  return files;
}

function readChapter(rel, n) {
  const xml = fs.readFileSync(path.join(SOURCE, rel), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const titleMatch = xml.match(/<chapter[^>]*>\s*<title>([\s\S]*?)<\/title>/);
  const chapter = { n, file: path.basename(rel), title: titleMatch ? plain(titleMatch[1]) : path.basename(rel) };

  const terms = [];
  const termRe = /<li xml:id="(term-[^"]+)">\s*<title>([\s\S]*?)<\/title>([\s\S]*?)<\/li>/g;
  let m;
  while ((m = termRe.exec(xml))) {
    const body = plain(m[3]);
    const sec = body.match(/\((§\s*[\d.]+(?:\s*,\s*§?\s*[\d.]+)*)\)\s*$/);
    terms.push({
      id: m[1],
      title: plain(m[2]),
      definition: sec ? body.slice(0, sec.index).trim() : body,
      section: sec ? sec[1].replace(/§\s*/g, '').replace(/\s*,\s*/g, ', ') : null,
      chapter: n,
    });
  }

  const prompts = [];
  const groupRe = /<exercisegroup[^>]*>\s*<title>([\s\S]*?)<\/title>([\s\S]*?)<\/exercisegroup>/g;
  while ((m = groupRe.exec(xml))) {
    const groupTitle = plain(m[1]);
    if (!/writing prompt/i.test(groupTitle)) continue;
    const intro = (m[2].match(/<introduction>([\s\S]*?)<\/introduction>/) || [])[1];
    const exRe = /<exercise xml:id="([^"]+)">([\s\S]*?)<\/exercise>/g;
    let e;
    while ((e = exRe.exec(m[2]))) {
      const statement = (e[2].match(/<statement>([\s\S]*?)<\/statement>/) || [, e[2]])[1];
      prompts.push({ id: e[1], chapter: n, chapterTitle: chapter.title, group: groupTitle, note: intro ? plain(intro) : '', text: plain(statement) });
    }
  }
  return { chapter, terms, prompts };
}

function umd(globalName, header, data) {
  return `/*
 * ${header}
 * GENERATED by book/scripts/build-writing-data.js from the PreTeXt source. Do not edit by hand.
 */
(function (root, data) {
  'use strict';
  if (typeof module === 'object' && module.exports) module.exports = data;
  else root.${globalName} = data;
})(typeof self !== 'undefined' ? self : this, ${JSON.stringify(data, null, 2)});
`;
}

function buildData() {
  const settings = JSON.parse(fs.readFileSync(path.join(OUT, 'concept-settings.json'), 'utf8'));
  const demo = new Set(settings.mayDemonstrate || []);
  const coreIds = new Set(settings.alwaysInFocus || []);
  const chapters = [];
  const concepts = [];
  const prompts = [];
  chapterFiles().forEach((rel, i) => {
    const r = readChapter(rel, i + 1);
    chapters.push(r.chapter);
    for (const t of r.terms) {
      concepts.push({
        ...t,
        family: settings.familyOverrides[t.id] || settings.familyByChapter[String(t.chapter)] || 'other',
        mode: demo.has(t.id) ? 'may-demonstrate' : 'ask',
        ...(coreIds.has(t.id) ? { core: true } : {}),
      });
    }
    prompts.push(...r.prompts);
  });
  for (const p of settings.provisional || []) {
    concepts.push({ id: p.id, title: p.title, definition: p.definition, section: null, chapter: 'writing', family: p.family || 'writing', mode: demo.has(p.id) ? 'may-demonstrate' : 'ask', provisional: true });
  }
  for (const p of settings.provisionalPrompts || []) {
    prompts.push({ id: p.id, chapter: 'writing', chapterTitle: 'Writing Arguments (provisional)', group: 'Writing Prompt', note: '', text: p.text, provisional: true });
  }
  const ids = concepts.map((c) => c.id);
  const dup = ids.find((id, i) => ids.indexOf(id) !== i);
  if (dup) throw new Error('Duplicate concept id: ' + dup);
  for (const id of [...demo, ...coreIds]) if (!ids.includes(id)) throw new Error('concept-settings.json names an unknown concept: ' + id);

  return {
    conceptsJs: umd('FeedbackConcepts', 'concepts.js — the book\'s Key Terms for the Argument Feedback tool.', { chapters, concepts }),
    promptsJs: umd('WritingPrompts', 'writing-prompts.js — the book\'s end-of-chapter Writing Prompts.', { prompts }),
    counts: { chapters: chapters.length, concepts: concepts.length, prompts: prompts.length },
  };
}

module.exports = { buildData, plain, OUT };

if (require.main === module) {
  const d = buildData();
  const targets = [['concepts.js', d.conceptsJs], ['writing-prompts.js', d.promptsJs]];
  if (process.argv.includes('--check')) {
    const stale = targets.filter(([f, s]) => !fs.existsSync(path.join(OUT, f)) || fs.readFileSync(path.join(OUT, f), 'utf8') !== s).map(([f]) => f);
    if (stale.length) { console.error('Stale: ' + stale.join(', ') + '. Run node book/scripts/build-writing-data.js'); process.exit(1); }
    console.log('Writing data is up to date.');
  } else {
    for (const [f, s] of targets) fs.writeFileSync(path.join(OUT, f), s);
    console.log(`Wrote concepts.js (${d.counts.concepts} concepts from ${d.counts.chapters} chapters) and writing-prompts.js (${d.counts.prompts} prompts).`);
  }
}
